"""Revision-aware scale-up and whole-job deletion using deployment operations."""
import copy
import hashlib
import uuid

from .deeploy_const import DEEPLOY_KEYS
from .deeploy_mixin import COCKROACHDB_CERT_ENV_KEYS, COCKROACHDB_BOOTSTRAP_CERT_ENV_KEYS
from .deeploy_job_mixin import DEEPLOY_JOBS_CSTORE_HKEY
from .deployment_operations import request_digest, replace_nodes, required_instances

# ChainDist publishes {job_id: (old_node, new_node)} here for jobs whose stored placement
# still names a node whose license its owner relinked to another node.
NODE_RELINKS_SHMEM_KEY = "CHAIN_DIST_NODE_RELINKS"
# Oracles take each job in hash order; a later one acts after waiting this long per rank.
NODE_RELINK_RANK_SECONDS = 900
# Each oracle looks at a job at most this often.
NODE_RELINK_RETRY_SECONDS = 300


class _DeploymentMutationsMixin:
  """Prepare mutations from exact persisted placement, never partial discovery."""

  def _mutation_baseline(self, request, owner, node_aliases=None):
    """Load and validate the exact current revision and every prior node config.

    Parameters
    ----------
    request : dict
      Authorized request with job_id and expected_revision.
    owner : str
      Authenticated escrow owner.
    node_aliases : dict, optional
      Old node -> new node for a relink; both the job and its node configs use the new node.

    Notes
    -----
    Only public redacted operation plans are loaded. Secret availability is
    established on dAuth during lifecycle preparation.
    """
    job_id = request.get("job_id")
    if job_id in (None, ""):
      raise ValueError("job_id is required for this deployment mutation.")
    pipeline = self.get_job_pipeline_from_cstore(job_id, timeout=30, pin=False,
                                                raise_on_error=False, show_logs=False)
    if not isinstance(pipeline, dict):
      raise ValueError("The current deployment configuration is unavailable.")
    pipeline = replace_nodes(pipeline, node_aliases or {})
    specs = pipeline.get("DEEPLOY_SPECS", {})
    if str(specs.get("job_id")) != str(job_id) or str(pipeline.get("OWNER", "")).lower() != owner.lower():
      raise ValueError("The current deployment does not belong to this job owner.")
    revision = specs.get("revision", 0)
    if type(request.get("expected_revision")) is not int or request["expected_revision"] != revision:
      raise ValueError("The deployment revision changed; refresh before changing it.")
    nodes = specs.get("current_target_nodes")
    if not isinstance(nodes, list) or not nodes or len(set(nodes)) != len(nodes):
      raise ValueError("The current deployment has no exact recoverable placement.")
    # For a relink the new node reports the config it inherited, still naming the old node.
    configs = replace_nodes(self._previous_deployment_configs(pipeline), node_aliases or {})
    if not isinstance(configs, dict) or set(configs) != set(nodes):
      raise ValueError("The current revision does not contain the complete placement.")
    expected_shape = [(plugin["SIGNATURE"], len(plugin["INSTANCES"])) for plugin in pipeline["PLUGINS"]]
    for config in configs.values():
      shape = [(plugin["SIGNATURE"], len(plugin["INSTANCES"])) for plugin in config.get("PLUGINS", [])]
      if shape != expected_shape:
        raise ValueError("The current node plugin layouts cannot be mapped safely for this mutation.")
      current_specs = config.get("DEEPLOY_SPECS", {})
      if (config.get("NAME") != pipeline["NAME"] or str(current_specs.get("job_id")) != str(job_id)
          or current_specs.get("revision", 0) != revision or not required_instances(config)):
        raise ValueError("A persisted node configuration does not match the current revision.")
    return copy.deepcopy(pipeline), {node: copy.deepcopy(configs[node]) for node in nodes}

  def _admit_scale_up_operation(self, request, auth_result, new_nodes):
    """Admit a full-placement update, retaining exact prior configs for recovery.

    The caller verifies payment, owner signature, and requested node resources.
    Existing identities and storage settings are preserved. Changes generated by
    managed-service preparation (including a new cluster CA) apply to all nodes.
    """
    owner = auth_result[DEEPLOY_KEYS.ESCROW_OWNER]
    existing = self._find_request_operation(request, owner, "update")
    if existing:
      return self._accepted_operation_response(existing)
    pipeline, previous = self._mutation_baseline(request, owner)
    if not isinstance(new_nodes, list) or not new_nodes or len(set(new_nodes)) != len(new_nodes) or set(new_nodes) & set(previous):
      raise ValueError("Scale-up requires distinct new nodes outside the current placement.")
    specs = pipeline["DEEPLOY_SPECS"]
    base = dict(base_pipeline=copy.deepcopy(pipeline), app_id=pipeline["NAME"],
                deeploy_specs=copy.deepcopy(specs), plugins=copy.deepcopy(pipeline["PLUGINS"]),
                pipeline_type=pipeline.get("TYPE", "void"), url=pipeline.get("URL"),
                pipeline_params=self._get_pipeline_params_from_deeploy_specs(specs) or {})
    original_plugins = copy.deepcopy(base["plugins"])
    aliases = {}
    created, _, _ = self.prepare_create_update_pipelines(
      base, new_nodes=new_nodes, update_nodes=[], running_apps_for_job={},
      generated_instance_identity_aliases=aliases,
    )
    new_configs = self._build_scale_up_create_pipeline_configs(created, owner)
    nodes = list(previous) + new_nodes
    configs = previous
    for config in configs.values():
      config.pop("DEEPLOY_OPERATION", None)
      config["DEEPLOY_SPECS"] = copy.deepcopy(base["deeploy_specs"])
      for plugin_index, plugin in enumerate(config["PLUGINS"]):
        for instance_index, instance in enumerate(plugin["INSTANCES"]):
          before = original_plugins[plugin_index]["INSTANCES"][instance_index]
          prepared = base["plugins"][plugin_index]["INSTANCES"][instance_index]
          # Preserve effective per-node settings while propagating newly
          # generated managed-service material from the common preparation.
          for key, value in prepared.get("ENV", {}).items():
            if before.get("ENV", {}).get(key) != value:
              instance.setdefault("ENV", {})[key] = copy.deepcopy(value)
          for key in ("PER_NODE_CONFIG", "per_node_config"):
            if prepared.get(key) != before.get(key):
              instance[key] = copy.deepcopy(prepared.get(key))
          instance["CHAINSTORE_PEERS"] = list(nodes)
          instance["PER_NODE_TARGET_NODES"] = list(nodes)
    configs.update(new_configs)
    for config in configs.values():
      config["DEEPLOY_SPECS"].update(current_target_nodes=list(nodes), nr_target_nodes=len(nodes))
      for plugin in config["PLUGINS"]:
        for instance in plugin["INSTANCES"]:
          # Runtime pins belong to their original node/attempt. New placement
          # resolves its requested image and captures a fresh exact binding.
          instance.pop("DEEPLOY_RUNTIME_ARTIFACTS", None)
          by_node = instance.get("PER_NODE_CONFIG", {}).get("byNode", {})
          if all(by_node.get(node, {}).get("ENV", {}).get("CRDB_CA_CRT") for node in nodes):
            # Every target receives its new certificate overlay. Remove old
            # direct credentials which would otherwise remain as unused secrets.
            for key in COCKROACHDB_CERT_ENV_KEYS + COCKROACHDB_BOOTSTRAP_CERT_ENV_KEYS:
              instance.get("ENV", {}).pop(key, None)
    return self._admit_prepared_deployment(
      request=request, auth_result=auth_result, app_id=pipeline["NAME"], configs=configs,
      prior_pipeline=pipeline, is_create=False,
      mutation="scale_up", identity_aliases=aliases,
    )

  def _admit_owner_transfer_operation(self, job_id, old_owner, new_owner, transfer_id):
    """Reconcile a verified escrow transfer through a complete revision rollout.

    Parameters
    ----------
    job_id : int
      Job returned by the verified escrow's active job list.
    old_owner, new_owner : str
      Addresses from the verified on-chain transfer event.
    transfer_id : str
      Stable transaction-hash/log-index identity from the verified event.

    Notes
    -----
    On-chain authorization has already changed. Recovery restores old runtime
    content while retaining the new owner, never reversing escrow authorization.
    """
    if not isinstance(transfer_id, str) or not transfer_id:
      raise ValueError("A verified owner-transfer event identity is required.")
    pipeline = self.get_job_pipeline_from_cstore(job_id, timeout=30, pin=False,
                                                raise_on_error=False, show_logs=False)
    if not isinstance(pipeline, dict):
      raise ValueError("The current deployment configuration is unavailable.")
    current_owner = pipeline.get("OWNER", "")
    if current_owner.lower() not in (old_owner.lower(), new_owner.lower()):
      raise ValueError("The current deployment owner no longer matches this transfer.")
    request_id = "owner-transfer-" + hashlib.sha256((str(job_id) + "|" + transfer_id).encode()).hexdigest()
    observed = next((record for record in self._operation_records().values()
                     if record.get("request_id") == request_id and str(record.get("job_id")) == str(job_id)
                     and record.get("owner", "").lower() == new_owner.lower()), None)
    revision = observed["previous_revision"] if observed else pipeline["DEEPLOY_SPECS"].get("revision", 0)
    request = dict(request_id=request_id, job_id=job_id, expected_revision=revision,
                   transfer_id=transfer_id, old_owner=old_owner, new_owner=new_owner)
    existing = self._find_request_operation(request, new_owner, "update")
    if existing:
      return self._accepted_operation_response(existing)
    self._assert_no_active_deployment(job_id=job_id)
    prior, configs = self._mutation_baseline(request, current_owner)
    for config in configs.values():
      config["OWNER"] = new_owner
      config["DEEPLOY_SPECS"]["date_updated"] = self.time()
      config.pop("DEEPLOY_OPERATION", None)
    return self._admit_prepared_deployment(
      request=request, auth_result={DEEPLOY_KEYS.ESCROW_OWNER: new_owner}, app_id=prior["NAME"],
      configs=configs, prior_pipeline=prior, is_create=False,
      mutation="owner_transfer", restore_owner=new_owner,
    )

  def _admit_node_relink_operation(self, job_id, old_node, new_node):
    """Move a job from a relinked node to its owner's new node through a revision rollout.

    Parameters
    ----------
    job_id : int
      Job whose stored placement still names the old node.
    old_node, new_node : str
      Internal addresses; ChainDist found the new node linked to the old node's
      license by the same owner.

    Notes
    -----
    The new node is the same machine with a new key, so it keeps the old node's
    settings, including per-node secrets, which dAuth moves with the same aliases.
    The old node is never contacted; the new node stops its current copy first.
    """
    pipeline = self.get_job_pipeline_from_cstore(job_id, timeout=30, pin=False,
                                                raise_on_error=False, show_logs=False)
    if not isinstance(pipeline, dict):
      raise ValueError("The current deployment configuration is unavailable.")
    specs = pipeline.get("DEEPLOY_SPECS", {})
    nodes = specs.get("current_target_nodes", [])
    if old_node not in nodes or new_node in nodes:
      raise ValueError("The stored placement does not name only the relinked node.")
    owner = pipeline.get("OWNER", "")
    request_id = "node-relink-" + hashlib.sha256("{}|{}|{}".format(job_id, old_node, new_node).encode()).hexdigest()
    request = dict(request_id=request_id, job_id=job_id, expected_revision=specs.get("revision", 0),
                   old_node=old_node, new_node=new_node)
    existing = self._find_request_operation(request, owner, "update")
    if existing:
      return self._accepted_operation_response(existing)
    self._assert_no_active_deployment(job_id=job_id)
    node_aliases = {old_node: new_node}
    prior, configs = self._mutation_baseline(request, owner, node_aliases=node_aliases)
    for config in configs.values():
      config["DEEPLOY_SPECS"]["date_updated"] = self.time()
      config.pop("DEEPLOY_OPERATION", None)
    return self._admit_prepared_deployment(
      request=request, auth_result={DEEPLOY_KEYS.ESCROW_OWNER: owner}, app_id=prior["NAME"],
      configs=configs, prior_pipeline=prior, is_create=False,
      mutation="node_relink", node_aliases=node_aliases,
    )

  def _maybe_admit_node_relinks(self):
    """Admit the relinks ChainDist found, one oracle per job.

    Online oracles are ranked per job by hash. The first acts at once and each
    later one only after waiting its rank, so a stopped oracle delays a job
    instead of blocking it, and overlaps resolve to the same request.
    """
    relinks = self.plugins_shmem.get(NODE_RELINKS_SHMEM_KEY) or {}
    now = self.time()
    seen = getattr(self, "_node_relinks_seen", {})
    self._node_relinks_seen = {job_id: seen.get(job_id, [now, now - NODE_RELINK_RETRY_SECONDS]) for job_id in relinks}
    due = [job_id for job_id, (_, last_check) in self._node_relinks_seen.items()
           if now - last_check >= NODE_RELINK_RETRY_SECONDS]
    if not due:
      return
    peers = [peer for peer in self._operation_peers()
             if peer == self.bc.address or self.netmon.network_node_is_online(peer)]
    for job_id in due:
      self._node_relinks_seen[job_id][1] = now
      ranked = sorted(peers, key=lambda peer: hashlib.sha256("{}|{}".format(job_id, peer).encode()).hexdigest())
      if now - self._node_relinks_seen[job_id][0] < ranked.index(self.bc.address) * NODE_RELINK_RANK_SECONDS:
        continue
      old_node, new_node = relinks[job_id]
      try:
        self._admit_node_relink_operation(job_id, old_node, new_node)
        self.P(f"Job {job_id}: moving relinked node {old_node} to {new_node}.")
      except Exception as exc:
        self.P(f"Job {job_id}: relinked node move not admitted: {exc}", color='y')
    return

  def _admit_delete_operation(self, request, auth_result):
    """Persist a whole-job scoped retirement before dispatching any stop."""
    owner = auth_result[DEEPLOY_KEYS.ESCROW_OWNER]
    existing = self._find_request_operation(request, owner, "delete")
    if existing:
      return self._accepted_operation_response(existing)
    if request.get("job_id") in (None, ""):
      raise ValueError("job_id is required for deletion.")
    details = self.bc.get_job_details(int(request["job_id"]))
    if str(details.get("escrowOwner", "")).lower() != owner.lower():
      raise ValueError("Only the current escrow owner can delete this deployment.")
    pipeline, configs = self._mutation_baseline(request, owner)
    if request.get("app_id") not in (None, pipeline["NAME"]):
      raise ValueError("app_id does not match the selected job.")
    targets = request.get("target_nodes")
    if targets is not None and (not isinstance(targets, list) or set(targets) != set(configs)):
      raise ValueError("Deletion must target the entire job placement.")
    specs = pipeline["DEEPLOY_SPECS"]
    reference = specs.get("secret_revision")
    # Preserve the prior reference: delete creates no new plaintext revision.
    for config in configs.values():
      config.pop("DEEPLOY_OPERATION", None)
    canonical_record = self.chainstore_hget(DEEPLOY_JOBS_CSTORE_HKEY, str(request["job_id"]))
    revision = self._next_deployment_revision(request["job_id"], specs.get("revision", 0))
    plan = dict(configs={}, previous_configs=configs, canonical_record=canonical_record,
                canonical_cid=self._get_pipeline_from_cstore(request["job_id"]))
    cid = self.r1fs.add_json(plan, nonce=42, fn="deployment-plan.json", show_logs=False)
    if not cid:
      raise RuntimeError("Could not persist deletion execution plan.")
    now = self.time()
    operation = dict(
      operation_id=hashlib.sha256(self.bc.address.encode()).hexdigest()[:16] + "-" + uuid.uuid4().hex,
      request_id=request["request_id"], request_hash=request_digest(request), kind="delete",
      job_id=request["job_id"], app_id=pipeline["NAME"], owner=owner, network=self.evm_network,
      coordinator=self.bc.address, target_revision=revision,
      previous_revision=specs.get("revision", 0), previous_operation_id=reference.split(":", 1)[0] if reference else None,
      previous_secret_revision=reference, previous_pipeline_cid=plan["canonical_cid"], plan_cid=cid, nodes=[], previous_nodes=list(configs),
      instances={}, previous_instances={node: required_instances(config) for node, config in configs.items()},
      phase="retiring_previous", outcome=None, recovery=None, created_at=now, updated_at=now,
      deadline=now + self.cfg_deployment_readiness_timeout, sequence=0, events=[], sent_at={},
      error=None,
    )
    self._save_operation(operation, message="Whole-job deletion accepted; awaiting confirmed shutdown.")
    self._deployment_operations_event.set()
    return self._accepted_operation_response(operation)

  def _advance_delete_operation(self, operation):
    """Revoke secrets and remove metadata only after every scoped stop is proven."""
    self._replicate_operation(operation)
    plan = self._load_operation_plan(operation)
    reports = self._node_operation_reports(operation, "retire")
    if not all(reports.get(node, {}).get("status") == "stopped" for node in plan["previous_configs"]):
      if self.time() >= operation["deadline"] or any(report.get("status") == "failed" for report in reports.values()):
        operation.update(recovery="blocked", error=dict(code="STOP_UNCONFIRMED",
                         message="Deletion is waiting for confirmed shutdown on every node.", retryable=True))
        self._save_operation(operation)
      self._send_operation_commands(operation, plan["previous_configs"], "retire", "retire", reports)
      return
    tombstone = dict(job_id=str(operation["job_id"]), deleted=True, pipeline_cid=None,
                     operation_id=operation["operation_id"], revision=operation["target_revision"],
                     coordinator=operation["coordinator"])
    self.bc.sign(tombstone, add_data=True, use_digest=True)
    self._deployment_secret_request("delete", operation, pointer=tombstone)
    operation.update(outcome="succeeded", recovery="completed", error=None)
    self._save_operation(operation, "completed", "Pipeline stopped on all nodes and protected metadata removed.")
