"""RM-120 phase 2 — framework pack integrity (`ro.dnsc.o1-2026`).

Verifies the committed pack and text JSON generated by the hub workbook
`project-red-mesh:workbooks/redmesh-framework-pack/`:
  - both files load through the cached loader and pass the shape checks;
  - 218 controls, 34/133/218 by level, 13/22/29 key measures, 15 management-aspect controls,
    22 categories, 90 subcategories;
  - every id has requirement and guidance text, every category and subcategory a title;
  - thresholds per level match the contract; acts and provenance are present;
  - no "CyFun" in the pack id (trademark rule).
"""
from __future__ import annotations

import json
import unittest

from extensions.business.cybersec.red_mesh.references.framework_packs import (
  FrameworkPackError,
  controls_for_level,
  list_framework_pack_ids,
  load_framework_pack,
  load_framework_text,
  reset_framework_caches,
)

PACK_ID = "ro.dnsc.o1-2026"
MANAGEMENT_ASPECT_IDS = [
  "DE.AE-04.1", "GV.RM-01.1", "GV.RM-02.1", "GV.RM-03.2", "GV.RR-02.1", "GV.RR-02.2", "GV.SC-01.1",
  "ID.IM-03.9", "ID.IM-04.1", "ID.IM-04.2", "ID.RA-05.2", "ID.RA-05.3", "ID.RA-06.1", "PR.IR-04.1",
  "RC.CO-03.1",
]


class TestPackLoads(unittest.TestCase):

  def setUp(self):
    reset_framework_caches()

  def test_pack_is_listed_and_loads(self):
    self.assertIn(PACK_ID, list_framework_pack_ids())
    pack = load_framework_pack(PACK_ID)
    self.assertEqual(pack["pack_id"], PACK_ID)
    self.assertEqual(pack["scoring"], "maturity_two_axis.v1")
    self.assertEqual(pack["language"], "ro")
    self.assertEqual(pack["levels"], ["basic", "important", "essential"])
    self.assertEqual(pack["acts"], ["MO 712 bis/2026-08-27", "MO 792/2026-09-18 (Ordin 2/2026)"])
    self.assertTrue(pack["provenance"]["sources"]["annex1"]["pinned"])
    self.assertNotIn("CyFun", pack["pack_id"])

  def test_unknown_pack_is_refused(self):
    with self.assertRaises(FrameworkPackError):
      load_framework_pack("cyfun.2025")
    with self.assertRaises(FrameworkPackError):
      load_framework_text("nope")

  def test_counts(self):
    pack = load_framework_pack(PACK_ID)
    self.assertEqual(len(pack["controls"]), 218)
    self.assertEqual(pack["counts"], {
      "controls": 218,
      "by_level": {"basic": 34, "important": 133, "essential": 218},
      "key_measures": {"basic": 13, "important": 22, "essential": 29},
      "management_aspect": 15,
      "categories": 22,
      "subcategories": 90,
    })
    for level, expected in (("basic", 34), ("important", 133), ("essential", 218)):
      self.assertEqual(len(controls_for_level(pack, level)), expected, level)
    km = {lvl: sum(1 for c in controls_for_level(pack, lvl) if c["key_measure"]) for lvl in pack["levels"]}
    self.assertEqual(km, {"basic": 13, "important": 22, "essential": 29})
    self.assertEqual(sorted(c["ref_id"] for c in pack["controls"] if c["management_aspect"]), MANAGEMENT_ASPECT_IDS)
    self.assertEqual(len({c["category"] for c in pack["controls"]}), 22)
    self.assertEqual(len({c["subcategory"] for c in pack["controls"]}), 90)

  def test_controls_are_in_annex_order_with_consistent_hierarchy(self):
    pack = load_framework_pack(PACK_ID)
    orders = [c["order"] for c in pack["controls"]]
    self.assertEqual(orders, list(range(1, 219)))
    for c in pack["controls"]:
      self.assertEqual(c["category"], c["ref_id"].split("-")[0], c["ref_id"])
      self.assertEqual(c["subcategory"], c["ref_id"].rsplit(".", 1)[0], c["ref_id"])
    self.assertEqual(pack["controls"][0]["ref_id"], "GV.OC-01.1")
    self.assertEqual(pack["controls"][-1]["ref_id"], "RC.RP-06.1")

  def test_thresholds_match_contract(self):
    th = load_framework_pack(PACK_ID)["thresholds"]
    self.assertEqual(th["basic"], {"key_measure_min": 2.5, "category_min": None, "total_min": 2.5,
                                   "excluded_value": 2.5, "max_excluded": 1})
    self.assertEqual(th["important"], {"key_measure_min": 3.0, "category_min": None, "total_min": 3.0,
                                       "excluded_value": 3.0, "max_excluded": 3})
    self.assertEqual(th["essential"], {"key_measure_min": 3.0, "category_min": 3.0, "total_min": 3.5,
                                       "excluded_value": 3.0, "max_excluded": 5,
                                       "management_aspect_excludable": False})


class TestTextLoads(unittest.TestCase):

  def setUp(self):
    reset_framework_caches()

  def test_every_control_has_text_and_titles_exist(self):
    pack = load_framework_pack(PACK_ID)
    text = load_framework_text(PACK_ID)
    self.assertEqual(text["language"], "ro")
    self.assertEqual(set(text["controls"]), {c["ref_id"] for c in pack["controls"]})
    for ref_id, entry in text["controls"].items():
      self.assertTrue(entry["requirement"].strip(), ref_id)
      self.assertTrue(entry["guidance"].strip(), ref_id)
    for c in pack["controls"]:
      self.assertTrue(text["categories"][c["category"]]["title"], c["category"])
      self.assertIn(c["subcategory"], text["subcategories"], c["subcategory"])
    self.assertEqual(set(text["functions"]), {"GV", "ID", "PR", "DE", "RS", "RC"})

  def test_maturity_levels_are_the_five_stages(self):
    text = load_framework_text(PACK_ID)
    self.assertEqual([m["name"] for m in text["maturity_levels"]],
                     ["Inițial", "Repetabil", "Definit", "Gestionat", "Optimizare"])
    for m in text["maturity_levels"]:
      self.assertTrue(m["documentation"] and m["implementation"], m["value"])

  def test_text_is_valid_utf8_json_with_diacritics(self):
    text = load_framework_text(PACK_ID)
    blob = json.dumps(text, ensure_ascii=False)
    self.assertIn("ș", blob)
    self.assertIn("ț", blob)


if __name__ == "__main__":
  unittest.main()
